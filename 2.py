def drawdown_curve(df, asset):

    growth = (

        1 +

        df["Strategy_Return"]

        .fillna(0)

    ).cumprod()

    rolling_max = (

        growth

        .cummax()

    )

    drawdown = (

        growth

        - rolling_max

    ) / rolling_max

    plt.figure(figsize=(14,6))

    plt.fill_between(

        drawdown.index,

        drawdown * 100,

        0,

        color="red",

        alpha=0.3

    )

    plt.plot(

        drawdown.index,

        drawdown * 100,

        color="darkred"

    )

    plt.title(
        f"{asset}: Drawdown Curve"
    )

    plt.ylabel(
        "Drawdown (%)"
    )

    plt.xlabel(
        "Date"
    )

    plt.grid(True)

    plt.show()

