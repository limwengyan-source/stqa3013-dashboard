#Technical Indicator

def add_indicators(df):

    df = df.copy()

    df["MA50"] = (

        df["Price"]

        .rolling(50)

        .mean()

    )

    df["MA200"] = (

        df["Price"]

        .rolling(200)

        .mean()

    )

    ema12 = df["Price"].ewm(

        span=12,

        adjust=False

    ).mean()

    ema26 = df["Price"].ewm(

        span=26,

        adjust=False

    ).mean()

    df["MACD"] = ema12 - ema26

    delta = df["Price"].diff()

    gain = delta.clip(lower=0)

    loss = -delta.clip(upper=0)

    rs = (

        gain.rolling(14).mean()

        /

        loss.rolling(14).mean()

    )

    df["RSI"] = (

        100 -

        100/(1+rs)

    )

    return df



