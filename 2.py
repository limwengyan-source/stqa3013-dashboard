def run_backtest(df):

    df = df.copy()

    df["Return"] = (

        df["Price"]

        .pct_change()

    )

    df["Position"] = (

        df["Signal"]

        .shift(1)

        .fillna(0)

    )

    trades = (

        df["Position"]

        .diff()

        .abs()

        .fillna(0)

    )

    cost = (

        trades

        * TRANSACTION_COST

    )

    df["Strategy_Return"] = (

        df["Position"]

        * df["Return"]

        - cost

    )

    df["Portfolio"] = (

        INITIAL_CAPITAL

        *

        (

            1 +

            df["Strategy_Return"]

            .fillna(0)

        ).cumprod()

    )

    return df

